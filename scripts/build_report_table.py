#!/usr/bin/env python3
"""Verify the frozen evo result bundle and reproduce its LaTeX table offline.

Uses only the Python standard library. Does not run VIO or recompute metrics.
"""
import argparse
import csv
import hashlib
import json
from pathlib import Path
import zipfile

ROOT = Path(__file__).resolve().parents[1]
METRICS = ['ape_position_m', 'ape_orientation_deg', 'rpe_position_m', 'rpe_orientation_deg']
SEQUENCES = ['1018_13', 'kaeb_1', 'offroad1']
NAMES = {'okvis1': 'OKVIS 1', 'orbslam3': 'ORB-SLAM3', 'voxel-svio': 'Voxel-SVIO'}


def require(condition, message):
    if not condition:
        raise ValueError(message)


def masked(row):
    return row['sequence'] == 'offroad1' and row['module'] == 'voxel-svio'


def matrix_table(rows):
    """One table: methods by rows; all four metrics grouped by sequence."""
    groups = [r'BotanicGarden (\texttt{1018\_13})',
              r'GrandTour (\texttt{kaeb\_1})', r'GEODE (Offroad1 $\gamma$)$^{\dagger}$']
    lines = [r'% Generated by build_tables.py. Requires booktabs and xcolor[table].',
             r'\begin{table}[tbp]', r'\centering', r'\scriptsize',
             r'\setlength{\tabcolsep}{2.5pt}', r'\renewcommand{\arraystretch}{1.15}',
             r'\caption{Сравнение stereo-inertial одометрии: RMSE, '
             r'$\mathrm{SE}(3)$ без коррекции масштаба; RPE на отрезках длиной 1~м.}',
             r'\label{tab:vio-reference-results}',
             r'\begin{tabular*}{\linewidth}{@{\extracolsep{\fill}}lrrrrrrrrrrrr@{}}',
             r'\toprule',
             ' & ' + ' & '.join(r'\multicolumn{4}{c}{' + g + '}' for g in groups) + r' \\',
             r'\cmidrule(lr){2-5}\cmidrule(lr){6-9}\cmidrule(lr){10-13}',
             'Метод & ' + ' & '.join([r'\multicolumn{2}{c}{APE $\downarrow$} & '
                                     r'\multicolumn{2}{c}{RPE $\downarrow$}'] * 3) + r' \\',
             r'\cmidrule(lr){2-3}\cmidrule(lr){4-5}\cmidrule(lr){6-7}'
             r'\cmidrule(lr){8-9}\cmidrule(lr){10-11}\cmidrule(lr){12-13}',
             ' & ' + ' & '.join(['[м]', r'[$^\circ$]', '[м]', r'[$^\circ$]'] * 3) + r' \\',
             r'\midrule']
    for index, method in enumerate(['voxel-svio', 'orbslam3', 'okvis1']):
        if index % 2:
            lines.append(r'\rowcolor{black!5}')
        name = NAMES[method] + (r'$^{*}$' if method == 'orbslam3' else '')
        cells = [name]
        for sequence in SEQUENCES:
            group = [r for r in rows if r['sequence'] == sequence]
            row = next(r for r in group if r['module'] == method)
            for metric in METRICS:
                if masked(row):
                    cells.append(r'$\times$')
                    continue
                value = round(row[metric + '_rmse'], 3)
                minimum = min(round(r[metric + '_rmse'], 3) for r in group if not masked(r))
                cell = f'{value:.3f}'
                cells.append(r'\textbf{' + cell + '}' if value == minimum else cell)
        lines.append(' & '.join(cells) + r' \\')
    lines += [r'\bottomrule', r'\end{tabular*}', r'\par\smallskip',
              r'\begin{minipage}{\linewidth}\footnotesize',
              r'$\times$ --- устойчивое прохождение не подтверждено. '
              r'Полужирным выделены минимумы после округления. Замыкание петель отключено.',
              r'\par $^{*}$ORB-SLAM3: оценка по ключевым кадрам; наборы timestamps различаются. '
              r'$^{\dagger}$GEODE: принята поправка ориентации GT; качество GNSS/INS и '
              r'калибровки независимо не подтверждено.',
              r'\end{minipage}', r'\end{table}', '']
    return '\n'.join(lines)


def verify(bundle):
    manifest = json.loads((bundle / 'bundle.json').read_text())
    require(manifest['schema_version'] == 1, 'Unsupported bundle schema')
    for name, record in manifest['files'].items():
        if name == 'vio_reference_table.tex':
            continue  # Generated below; all of its inputs are verified first.
        require(hashlib.sha256((bundle / name).read_bytes()).hexdigest() == record['sha256'],
                f'Artifact hash mismatch: {name}')
    sources = json.loads((bundle / 'sources.json').read_text())
    rows = sources['rows']
    require(len(rows) == 9 and {(r['sequence'], r['module']) for r in rows} ==
            {(s, m) for s in SEQUENCES for m in NAMES}, 'Expected nine unique results')
    bindings = {(r['sequence'], r['module']): r['directory'] for r in manifest['evaluations']}
    with (bundle / 'reference_results.csv').open() as stream:
        csv_rows = {(r['sequence'], r['module']): r for r in csv.DictReader(stream)}
    for row in rows:
        key = row['sequence'], row['module']
        folder = bundle / bindings[key]
        summary = json.loads((folder / 'summary.json').read_text())
        require(hashlib.sha256((folder / 'summary.json').read_bytes()).hexdigest() ==
                row['summary_sha256'], f'Original summary changed: {key}')
        for name, value in sources['protocol'].items():
            require(summary['protocol'][name] == value, f'Protocol mismatch: {key}/{name}')
        for metric in METRICS:
            expected = row[metric + '_rmse']
            with zipfile.ZipFile(folder / (metric + '.zip')) as archive:
                rmse = json.loads(archive.read('stats.json'))['rmse']
            for actual in [rmse, summary['metrics'][metric]['rmse'],
                           float(csv_rows[key][metric + '_rmse'])]:
                require(abs(actual - expected) < 1e-10, f'Metric mismatch: {key}/{metric}')
    return rows


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--bundle', type=Path, default=ROOT / 'artifacts/report')
    parser.add_argument('--check', action='store_true', help='Verify without writing files')
    args = parser.parse_args()
    rows = verify(args.bundle)
    table = matrix_table(rows)
    manifest = json.loads((args.bundle / 'bundle.json').read_text())
    require(hashlib.sha256(table.encode()).hexdigest() ==
            manifest['files']['vio_reference_table.tex']['sha256'], 'Generated table hash differs')
    target = args.bundle / 'vio_reference_table.tex'
    if args.check:
        require(target.read_text() == table, 'LaTeX table differs from verified source metrics')
    else:
        target.write_text(table)
    print('Verified 9 results, 36 evo ZIP metrics and artifact hashes; table matches report.')


if __name__ == '__main__':
    main()
